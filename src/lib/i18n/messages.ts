/** A date in the visitor's language, e.g. 19 Nov 2026 / 19 พ.ย. 2569. */
export const formatDate = (value: string | Date, locale: Locale) =>
  new Date(value).toLocaleDateString(locale === "th" ? "th-TH" : "en-GB", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
